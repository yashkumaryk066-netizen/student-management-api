class ReportDownloadView(APIView):
    permission_classes = [IsAuthenticated]
    
    def get(self, request, pk):
        report = get_object_or_404(GeneratedReport, pk=pk)
        
        # Verify ownership
        if report.user != request.user and not request.user.is_superuser:
            return Response({"error": "Access Denied"}, status=403)

        # Serve File
        from django.core.files.storage import default_storage
        if default_storage.exists(report.file_url):
             file = default_storage.open(report.file_url, 'rb')
             response = HttpResponse(file, content_type='application/pdf')
             response['Content-Disposition'] = f'attachment; filename="{report.name}.pdf"'
             return response
        else:
             return Response({"error": "File not found"}, status=404)
