def haversine(lon1, lat1, lon2, lat2):
    """
    Calculate the great circle distance between two points 
    on the earth (specified in decimal degrees)
    """
    # Convert decimal degrees to radians 
    lon1, lat1, lon2, lat2 = map(radians, [float(lon1), float(lat1), float(lon2), float(lat2)])

    # Haversine formula 
    dlon = lon2 - lon1 
    dlat = lat2 - lat1 
    a = sin(dlat/2)**2 + cos(lat1) * cos(lat2) * sin(dlon/2)**2
    c = 2 * asin(sqrt(a)) 
    r = 6371 # Radius of earth in kilometers. Use 3956 for miles
    return c * r * 1000 # Return meters

def validate_coordinates(lat, lon):
    """
    Validate latitude (-90 to 90) and longitude (-180 to 180)
    """
    try:
        lat_f = float(lat)
        lon_f = float(lon)
        if not (-90 <= lat_f <= 90 and -180 <= lon_f <= 180):
            return False
        return True
    except (ValueError, TypeError):
        return False

def draw_header_footer(canvas, doc, profile=None):
    canvas.saveState()
    
    # --- HEADER BACKGROUND ---
    # Premium Blue Header Strip
    canvas.setFillColor(colors.HexColor("#1a237e")) # Deep Royal Blue
    canvas.rect(0, 10.5*inch, 8.5*inch, 1.5*inch, fill=1, stroke=0)
    
    # --- LOGO & BRANDING ---
    inst_name = "Y.S.M"
    inst_sub = "ADVANCE EDUCATION SYSTEM"
    logo_path = None
    
    if profile:
        inst_name = profile.institution_name or "Y.S.M"
        inst_sub = f"{profile.institution_type} MANAGEMENT SYSTEM"
        if profile.institution_logo and hasattr(profile.institution_logo, 'path'):
            import os
            if os.path.exists(profile.institution_logo.path):
                logo_path = profile.institution_logo.path

    canvas.setFillColor(colors.white)
    
    # Draw Logo
    text_x = 0.5*inch
    if logo_path:
        try:
            canvas.drawImage(logo_path, 0.5*inch, 10.7*inch, width=0.7*inch, height=0.7*inch, mask='auto', preserveAspectRatio=True)
            text_x = 1.4*inch
        except: pass

    canvas.setFont("Helvetica-Bold", 22)
    canvas.drawString(text_x, 11*inch, inst_name.upper())
    canvas.setFont("Helvetica", 10)
    canvas.drawString(text_x, 10.8*inch, inst_sub)
    
    # --- INVOICE LABEL ---
    canvas.setFont("Helvetica-Bold", 36)
    canvas.setFillColor(colors.HexColor("#ffd700")) # Gold Color
    canvas.drawRightString(7.8*inch, 11*inch, "INVOICE")
    
    # --- FOOTER ---
    # Bottom Blue Strip
    canvas.setFillColor(colors.HexColor("#1a237e"))
    canvas.rect(0, 0, 8.5*inch, 0.8*inch, fill=1, stroke=0)
    
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica", 9)
    footer_text = f"Official Invoice generated by {inst_name}"
    canvas.drawCentredString(4.125*inch, 0.45*inch, footer_text)
    canvas.drawCentredString(4.125*inch, 0.3*inch, "Powered by Y.S.M Education System | support@ysm.education")
    
    canvas.restoreState()

