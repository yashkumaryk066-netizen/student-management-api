def get_owner_user(user):
    """
    Get the owner user for data filtering (multi-tenancy isolation).
    Centralized in utils.py to prevent circular imports between models and views.
    """
    if not user or not user.is_authenticated:
        return None
        
    if user.is_superuser:
        return user
    
    # 1. Check Student Profile
    if hasattr(user, 'student_profile'):
        return user.student_profile.created_by
        
    # 2. Check Employee Profile (Teacher/Staff)
    if hasattr(user, 'employee_profile'):
        return user.employee_profile.created_by
        
    # 3. Check Parent Role
    try:
        if hasattr(user, 'profile') and user.profile.role == 'PARENT':
            from student.models import Student
            child = Student.objects.filter(parent=user).first()
            if child:
                return child.created_by
    except:
        pass

    # 4. If current user is the Client/Admin (Owner)
    try:
        from django.core.exceptions import ObjectDoesNotExist
        profile = user.profile
        if profile.role in ['CLIENT', 'ADMIN']:
            return user
    except ObjectDoesNotExist:
        pass
        
    return user

def filter_by_owner(qs, user, created_by_field='created_by'):
    """
    Filter queryset to show only data owned by the current institution owner.
    SuperUser bypass: Returns unfiltered queryset for full system access.
    """
    # GOD MODE: SuperUser sees everything
    if user.is_superuser:
        return qs
    
    owner = get_owner_user(user)
    if owner:
        return qs.filter(**{created_by_field: owner})
    return qs.none()

